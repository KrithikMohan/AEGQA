"""Fit a user function with an amplitude-encoded quantum genetic algorithm.

Quantum offspring are generated by measured Qiskit Aer circuits; fitness and
elitist selection are classical. See AEQGA_USAGE.md for the public interface
and the implementation choices that extend the paper to general functions.
"""

from __future__ import annotations

import csv
from collections.abc import Callable, Sequence
from numbers import Integral
from pathlib import Path

import numpy as np
from qiskit import QuantumCircuit, transpile
from qiskit_aer import AerSimulator
from scipy.linalg import solve_triangular

from aeqga_parallel import circuit_groups, pack_circuits, positive_integer


class AEQGA:
    """Fit ``function(x_list, p_list)`` by minimizing a squared-error loss.

    By default, ``x_list`` contains one sample's features and the function must
    return one real scalar. With ``vectorized=True`` it receives the complete
    input batch as a list and must return one prediction per sample.

    Args:
        function: Model function. It should be deterministic, have no side
            effects, and be defined throughout the search bounds.
        p: Nonempty list of initial parameter values; included in the initial
            population. Subsequent train calls start from the current best p.
        bounds: One finite (lower, upper) pair per parameter, lower < upper.
        population_size: Power of two, at least 8. Offspring groups smaller
            than four are zero-padded to two qubits. Default: 32.
        elite_count: Number preserved unchanged; default population_size // 4.
            Must be at least one to retain the best solution.
        local_count: Number searched near the elites; default population_size // 4.
        random_count: Number initialized randomly for global quantum search;
            default population_size // 2. Local/random counts may be zero.
            The three counts must sum to population_size. Non-power-of-two
            offspring groups are zero-padded for encoding and trimmed after decoding.
        shots: Measurements per circuit. Default: 1024.
        parallel_circuits: Maximum independent circuits from one generation
            packed onto disjoint qubits in one execution. Default: 1.
        max_parallel_qubits: Optional active-qubit budget for each packed
            execution. Groups that exceed it are split, preserving input order.
        crossover_probability: Probability of applying both CRy(pi/2) gates.
        mutation_probability: Probability of applying an Rx(pi/2) gate.
        local_padding: Extend the elite min/max interval on each side by this
            fraction of its width. The paper leaves the box width unspecified.
        min_local_width: Minimum local interval width as a fraction of the
            global bound width, before padding; default 0.01 prevents premature
            collapse. Reduce it for finer searches once a suitable basin is found.
        vectorized: Whether the function evaluates the whole batch at once.
        seed: Seed for population generation, gate choices and Aer sampling.

    Attributes after train:
        p / get_p(): Copy of the best parameter list.
        loss_: Best SSE, or chi-square when sigma/covariance is provided.
        history_: Each generation's best loss/p plus the complete evaluated
            population (each candidate's p, loss and chi2), including gen. 0.
            chi2 is None for unweighted SSE; loss_kind identifies the objective.
        n_generations_: Number of completed evolutionary updates.
        n_evaluations_: Number of candidate fitness evaluations.
        quantum_circuits_: Number of logical offspring circuits sampled.
        executed_circuits_: Number of packed circuits actually executed.
        execution_history_: Per-generation packing, placement and raw counts.
        execution_circuits_: Executable circuits from the most recent generation.
    """

    def __init__(
        self,
        function: Callable,
        p: Sequence[float],
        *,
        bounds: Sequence[Sequence[float]],
        population_size: int = 32,
        elite_count: int | None = None,
        local_count: int | None = None,
        random_count: int | None = None,
        shots: int = 1024,
        parallel_circuits: int = 1,
        max_parallel_qubits: int | None = None,
        crossover_probability: float = 0.5,
        mutation_probability: float = 0.5,
        local_padding: float = 0.5,
        min_local_width: float = 0.01,
        vectorized: bool = False,
        seed: int | None = None,
    ) -> None:
        if not callable(function):
            raise TypeError("function must be callable: function(x_list, p_list).")
        parameters = self._real_array(p, "p")
        if parameters.ndim != 1 or parameters.size == 0:
            raise ValueError("p must be a nonempty one-dimensional parameter list.")
        intervals = self._real_array(bounds, "bounds")
        if intervals.shape != (parameters.size, 2):
            raise ValueError("bounds must contain one (lower, upper) pair per parameter.")
        if np.any(intervals[:, 0] >= intervals[:, 1]):
            raise ValueError("Every lower bound must be strictly less than its upper bound.")
        with np.errstate(over="ignore"):
            widths = intervals[:, 1] - intervals[:, 0]
        if not np.all(np.isfinite(widths)):
            raise ValueError("The differences between bounds must be finite.")
        if np.any(parameters < intervals[:, 0]) or np.any(parameters > intervals[:, 1]):
            raise ValueError("Initial p must lie within bounds.")
        self._positive_integer(population_size, "population_size")
        if population_size < 8 or population_size & (population_size - 1):
            raise ValueError("population_size must be a power of two and at least 8.")
        counts = {
            "elite_count": population_size // 4 if elite_count is None else elite_count,
            "local_count": population_size // 4 if local_count is None else local_count,
            "random_count": population_size // 2 if random_count is None else random_count,
        }
        self._positive_integer(counts["elite_count"], "elite_count")
        for name in ("local_count", "random_count"):
            value = counts[name]
            if isinstance(value, bool) or not isinstance(value, Integral) or value < 0:
                raise ValueError(f"{name} must be a nonnegative integer.")
        if sum(counts.values()) != population_size:
            raise ValueError("elite_count + local_count + random_count must equal population_size.")
        self._positive_integer(shots, "shots")
        parallel_circuits = positive_integer(parallel_circuits, "parallel_circuits")
        if max_parallel_qubits is not None:
            max_parallel_qubits = positive_integer(max_parallel_qubits, "max_parallel_qubits")
        for name, value in (
            ("crossover_probability", crossover_probability),
            ("mutation_probability", mutation_probability),
        ):
            if not np.isfinite(value) or not 0 <= value <= 1:
                raise ValueError(f"{name} must be between 0 and 1.")
        if not np.isfinite(local_padding) or not 0 <= local_padding <= 1:
            raise ValueError("local_padding must be between 0 and 1.")
        if not np.isfinite(min_local_width) or not 0 < min_local_width <= 1:
            raise ValueError("min_local_width must be in (0, 1].")
        if not isinstance(vectorized, bool):
            raise TypeError("vectorized must be a bool.")
        if seed is not None and (
            isinstance(seed, bool) or not isinstance(seed, Integral) or seed < 0
        ):
            raise ValueError("seed must be a nonnegative integer or None.")

        self.function = function
        self._p = parameters.copy()
        self._lower = intervals[:, 0].copy()
        self._upper = intervals[:, 1].copy()
        self._width = widths
        self.population_size = int(population_size)
        self.elite_count = int(counts["elite_count"])
        self.local_count = int(counts["local_count"])
        self.random_count = int(counts["random_count"])
        self.shots = int(shots)
        self.parallel_circuits = parallel_circuits
        self.max_parallel_qubits = max_parallel_qubits
        self.crossover_probability = float(crossover_probability)
        self.mutation_probability = float(mutation_probability)
        self.local_padding = float(local_padding)
        self.min_local_width = float(min_local_width)
        self.vectorized = vectorized
        self.seed = None if seed is None else int(seed)
        # MPS exploits the disconnected small blocks of a packed circuit.
        # A dense statevector would use exponential memory in the total width.
        self._backend = AerSimulator(
            method="matrix_product_state" if parallel_circuits > 1 else "statevector",
            max_parallel_threads=1)
        self.loss_: float | None = None
        self.loss_kind_: str | None = None
        self.history_: list[dict] = []
        self.n_generations_ = 0
        self.n_evaluations_ = 0
        self.quantum_circuits_ = 0
        self.executed_circuits_ = 0
        self.execution_history_: list[dict] = []
        self.execution_circuits_: list[QuantumCircuit] = []

    @property
    def p(self) -> list[float]:
        """Return a defensive copy of the current best parameters."""
        return self._p.tolist()

    def get_p(self) -> list[float]:
        """Method-style alternative to the p property."""
        return self.p

    def export_population_history(
        self, path: str | Path, *, parameter_names: Sequence[str] | None = None,
    ) -> Path:
        """Export one CSV row per candidate per generation, including generation 0.

        Columns: generation, individual (zero-based within each generation),
        parameter names, and chi2 or sse depending on the training objective.
        Individual is a row index, not a persistent lineage ID. Invalid numerical
        candidates retain their infinite loss. All retained elites are included.
        """
        if not self.history_:
            raise ValueError("No training history to export. Train first.")
        names = ([f"p_{i}" for i in range(self._p.size)]
                 if parameter_names is None else list(parameter_names))
        if (len(names) != self._p.size
                or not all(isinstance(name, str) and name.strip() for name in names)
                or len(set(names)) != len(names)
                or set(names) & {"generation", "individual", "chi2", "sse"}):
            raise ValueError("parameter_names must be unique nonempty names, one per parameter, "
                             "excluding generation, individual, chi2 and sse.")
        output = Path(path).expanduser().resolve()
        output.parent.mkdir(parents=True, exist_ok=True)
        with output.open("w", newline="", encoding="utf-8") as stream:
            writer = csv.writer(stream)
            writer.writerow(["generation", "individual", *names, self.loss_kind_])
            for record in self.history_:
                for individual, candidate in enumerate(record["population"]):
                    writer.writerow([record["generation"], individual,
                                     *candidate["p"], candidate["loss"]])
        return output

    def export_history_plot(
        self,
        path: str | Path,
        *,
        parameter_indices: Sequence[int] | None = None,
        parameter_names: Sequence[str] | None = None,
        include_loss: bool = True,
        include_initial: bool = False,
        title: str = "AEQGA best solution by generation",
        loss_label: str = "Best loss",
        dpi: int = 180,
    ) -> Path:
        """Save line plots of each generation's best solution and return its path.

        Each selected parameter has its own axis, since units/scales can differ.
        parameter_names, when supplied, labels ALL parameters in their original
        order; parameter_indices selects which to draw (default: all).
        By default generation zero is excluded: 1000 updates produce 1000 points.
        The optional loss panel shows the objective value of the same solution.
        Parameters need not be monotonic even though the best loss is monotonic.
        Uses an off-screen canvas, without opening a window or changing pyplot's
        global backend. Supports Matplotlib formats, e.g. PNG and SVG.
        """
        from matplotlib.backends.backend_agg import FigureCanvasAgg
        from matplotlib.figure import Figure

        records = [h for h in self.history_ if include_initial or h["generation"] > 0]
        if not records:
            raise ValueError("No generations to plot. Train first, or set include_initial=True.")
        self._positive_integer(dpi, "dpi")
        indices = list(range(self._p.size)) if parameter_indices is None else list(parameter_indices)
        if any(isinstance(i, bool) or not isinstance(i, Integral) or
               not 0 <= i < self._p.size for i in indices):
            raise ValueError("parameter_indices must contain valid parameter indices.")
        if len(set(indices)) != len(indices):
            raise ValueError("parameter_indices must not contain duplicates.")
        if not indices and not include_loss:
            raise ValueError("Select at least one parameter or include_loss=True.")
        names = [f"p[{i}]" for i in range(self._p.size)] if parameter_names is None else list(parameter_names)
        if len(names) != self._p.size or not all(isinstance(name, str) for name in names):
            raise ValueError("parameter_names must contain one string per model parameter.")
        output = Path(path).expanduser().resolve()
        if not output.suffix:
            raise ValueError("Provide a filename extension, such as .png or .svg.")
        panels = len(indices) + int(include_loss)
        figure = Figure(figsize=(10.5, 2.8 * panels + 0.8), layout="constrained")
        FigureCanvasAgg(figure)
        axes = figure.subplots(panels, 1, sharex=True, squeeze=False).ravel()
        generations = np.array([h["generation"] for h in records])
        colors = ["#176b9b", "#158575", "#a45b28", "#7156a5"]
        series = [(names[i], np.array([h["p"][i] for h in records])) for i in indices]
        if include_loss:
            series.append((loss_label, np.array([h["loss"] for h in records])))
        for index, (axis, (label, values)) in enumerate(zip(axes, series)):
            color = colors[index % len(colors)]
            axis.plot(generations, values, color=color, linewidth=1.7)
            axis.scatter(generations[-1], values[-1], color=color, s=25, zorder=3)
            axis.set_ylabel(label)
            axis.set_title(f"Final: {values[-1]:.8g}", loc="right", fontsize=10, color=color)
            axis.ticklabel_format(axis="y", style="plain", useOffset=False)
            axis.grid(True, alpha=0.2)
            axis.spines[["top", "right"]].set_visible(False)
            axis.margins(x=0.015)
        axes[-1].set_xlabel("Generation")
        figure.suptitle(title, fontsize=14, fontweight="bold")
        output.parent.mkdir(parents=True, exist_ok=True)
        try:
            figure.savefig(output, dpi=dpi, facecolor="white")
        finally:
            figure.clear()
        return output

    def predict(self, x: Sequence) -> np.ndarray:
        """Predict with current p, including before training (initial p)."""
        values = self._predict(self._inputs(x), self._p)
        if not np.all(np.isfinite(values)):
            raise ValueError("The model returned non-finite predictions for current p.")
        return values

    def train(
        self,
        x: Sequence,
        y: Sequence[float],
        *,
        generations: int = 100,
        sigma: float | Sequence[float] | None = None,
        covariance: Sequence[Sequence[float]] | None = None,
        target_loss: float | None = None,
        verbose: bool = False,
    ) -> AEQGA:
        """Run AEQGA and return self.

        x: A one-dimensional list of inputs, or rows of feature lists (n, d).
            In default mode, a scalar input is delivered to function as [x_i].
        y: One real target per input sample, shape (n,).
        sigma: Positive scalar or (n,) standard deviations; loss is sum((r/s)^2).
        covariance: Positive-definite (n, n) covariance; loss is r.T C^-1 r.
            Mutually exclusive with sigma. Without either, loss is sum(r^2).
        target_loss: Optional absolute loss threshold for early stopping.

        Each call creates a fresh population that includes the current p and
        replaces training history. Initial population is generation zero.
        All new offspring, including those in the final generation, are scored.
        Non-finite numeric predictions receive infinite loss; shape errors and
        exceptions in the user's function are reported rather than hidden.
        """
        self._positive_integer(generations, "generations")
        inputs = self._inputs(x)
        targets = self._real_array(y, "y")
        if targets.shape != (len(inputs),):
            raise ValueError("y must be a one-dimensional list with one target per sample.")
        if target_loss is not None and (
            not np.isfinite(target_loss) or target_loss < 0
        ):
            raise ValueError("target_loss must be finite and nonnegative, or None.")
        scale, cholesky = self._weights(len(targets), sigma, covariance)
        rng = np.random.default_rng(self.seed)
        population = rng.uniform(
            self._lower, self._upper, size=(self.population_size, self._p.size)
        )
        population[0] = self._p
        self.loss_ = None
        self.loss_kind_ = "chi2" if sigma is not None or covariance is not None else "sse"
        self.history_ = []
        self.n_generations_ = self.n_evaluations_ = self.quantum_circuits_ = 0
        self.executed_circuits_ = 0
        self.execution_history_ = []
        self.execution_circuits_ = []
        self._n_features = 1 if inputs.ndim == 1 else inputs.shape[1]

        def evaluate(candidates: np.ndarray) -> np.ndarray:
            losses = np.empty(len(candidates))
            for i, parameters in enumerate(candidates):
                prediction = self._predict(inputs, parameters)
                self.n_evaluations_ += 1
                if not np.all(np.isfinite(prediction)):
                    losses[i] = np.inf
                    continue
                with np.errstate(over="ignore", invalid="ignore", divide="ignore"):
                    residual = prediction - targets
                    if scale is not None:
                        residual = residual / scale
                    elif cholesky is not None:
                        residual = solve_triangular(
                            cholesky, residual, lower=True, check_finite=False
                        )
                    value = float(residual @ residual)
                losses[i] = value if np.isfinite(value) else np.inf
            return losses

        losses = evaluate(population)
        if not np.any(np.isfinite(losses)):
            raise ValueError("All initial candidates have non-finite loss. Check function and bounds.")
        self._record(population, losses, generation=0, verbose=verbose)
        elite_size = self.elite_count
        for generation in range(1, int(generations) + 1):
            if target_loss is not None and self.loss_ <= target_loss:
                break
            order = np.argsort(losses, kind="stable")
            elites = population[order[:elite_size]].copy()
            elite_losses = losses[order[:elite_size]].copy()
            # Preserve finite elites if fewer than elite_size candidates are valid.
            valid = np.flatnonzero(np.isfinite(elite_losses))
            invalid = np.flatnonzero(~np.isfinite(elite_losses))
            if invalid.size:
                replacements = rng.choice(valid, size=invalid.size, replace=True)
                elites[invalid] = elites[replacements]
                elite_losses[invalid] = elite_losses[replacements]
            random_part = rng.uniform(
                self._lower, self._upper,
                size=(self.random_count, self._p.size),
            )
            local, global_part = self._quantum_offspring(elites, random_part, rng)
            offspring = np.vstack((local, global_part))
            population = np.vstack((elites, offspring))
            # Unmodified elite scores are cached; every new individual is scored.
            losses = np.concatenate((elite_losses, evaluate(offspring)))
            self._record(population, losses, generation, verbose)
        return self

    def _quantum_offspring(self, elites, random_part, rng):
        # Repeat elites in fitness order, or take the best subset if fewer local
        # offspring are requested. Preserve the original ordering for equal sizes.
        local_parents = elites[np.arange(self.local_count) % len(elites)]
        local = np.empty((self.local_count, self._p.size))
        global_part = np.empty_like(random_part)
        circuits = []
        groups = []
        for dimension in range(self._p.size):
            if self.local_count:
                circuits.append(self._circuit(local_parents[:, dimension], rng))
                circuits[-1].metadata = {"parameter_index": dimension, "branch": "local"}
                groups.append((True, dimension, self.local_count))
            if self.random_count:
                circuits.append(self._circuit(random_part[:, dimension], rng))
                circuits[-1].metadata = {"parameter_index": dimension, "branch": "global"}
                groups.append((False, dimension, self.random_count))
        if not circuits:
            return local, global_part
        circuit_seed = int(rng.integers(0, 2**31 - 1))
        histograms = self._measure_circuits(circuits, circuit_seed, rng)
        self.quantum_circuits_ += len(circuits)
        for index, (is_local, dimension, count) in enumerate(groups):
            # Decode the full measured state space, including padding, so local
            # probabilities remain count_i / shots. Then keep exactly count rows.
            counts = self._counts(histograms[index], 1 << circuits[index].num_qubits)
            if is_local:
                lo, hi = self._local_box(elites[:, dimension], dimension)
                local[:, dimension] = self._decode(counts, lo, hi, True, rng)[:count]
            else:
                global_part[:, dimension] = self._decode(
                    counts, self._lower[dimension], self._upper[dimension], False, rng
                )[:count]
        return local, global_part

    def _prepare_execution(self, circuits, seed):
        groups = circuit_groups(circuits, self.parallel_circuits, self.max_parallel_qubits)
        compiled = self._compile_circuits(circuits, seed)
        return [pack_circuits([compiled[i] for i in group], group) for group in groups]

    def _measure_circuits(self, circuits, seed, rng):
        bundles = self._prepare_execution(circuits, seed)
        sampling_seed = int(rng.integers(0, 2**31 - 1))
        executable = [bundle.circuit for bundle in bundles]
        result = self._backend.run(executable, shots=self.shots,
                                   seed_simulator=sampling_seed).result()
        if not result.success:
            raise RuntimeError(f"Aer simulation failed: {result.status}")
        histograms, executions = [None] * len(circuits), []
        for index, bundle in enumerate(bundles):
            raw = dict(result.get_counts(index))
            if sum(raw.values()) != self.shots:
                raise RuntimeError("The returned shot count differs from the requested shots.")
            for source, counts in bundle.split_counts(raw).items():
                histograms[source] = counts
            executions.append({"execution_index": index,
                "active_qubits": bundle.active_qubits,
                "register_qubits": bundle.circuit.num_qubits,
                "depth": bundle.circuit.depth(), "gate_counts": dict(bundle.circuit.count_ops()),
                "blocks": bundle.blocks, "counts": raw})
        if any(counts is None for counts in histograms):
            raise RuntimeError("A logical circuit is missing its measurement result.")
        self.executed_circuits_ += len(bundles)
        self.execution_circuits_ = executable
        self.execution_history_.append({"generation": self.n_generations_+1,
            "parallel_circuits": self.parallel_circuits,
            "shots_per_logical_circuit": self.shots, "transpiler_seed": seed,
            "sampling_seed": sampling_seed, "executions": executions})
        return histograms

    def _compile_circuits(self, circuits, seed):
        """Compile a generation; subclasses may select an explicit gate basis."""
        return transpile(circuits, self._backend, optimization_level=0,
                         seed_transpiler=seed, num_processes=1)

    def _circuit(self, values: np.ndarray, rng) -> QuantumCircuit:
        """Paper Eqs. (11)-(15): direct amplitudes, two CRy gates and Rx."""
        n_qubits = max(2, (int(values.size) - 1).bit_length())
        values = np.pad(values, (0, (1 << n_qubits) - values.size))
        # Scaling first avoids overflow/underflow and leaves x / ||x|| unchanged.
        largest = np.max(np.abs(values))
        if largest == 0:
            amplitudes = np.full(values.size, 1 / np.sqrt(values.size))
        else:
            scaled = values / largest
            amplitudes = scaled / np.linalg.norm(scaled)
        circuit = QuantumCircuit(n_qubits)
        circuit.initialize(amplitudes, range(n_qubits))
        if rng.random() < self.crossover_probability:
            control, target = (int(q) for q in rng.choice(n_qubits, 2, replace=False))
            circuit.cry(np.pi / 2, control, target)
            circuit.cry(np.pi / 2, target, control)
        if rng.random() < self.mutation_probability:
            circuit.rx(np.pi / 2, int(rng.integers(n_qubits)))
        circuit.measure_all()
        return circuit

    def _local_box(self, values, dimension):
        lo, hi = float(np.min(values)), float(np.max(values))
        width = max(hi - lo, self.min_local_width * self._width[dimension])
        center = lo / 2 + hi / 2
        half_width = (0.5 + self.local_padding) * width
        return (
            max(self._lower[dimension], center - half_width),
            min(self._upper[dimension], center + half_width),
        )

    @staticmethod
    def _counts(counts, size):
        # Missing bitstrings have zero counts; int(bitstring, 2) follows Qiskit's
        # basis-index ordering (q0 is the least significant bit).
        result = np.zeros(size, dtype=float)
        for bitstring, count in counts.items():
            result[int(bitstring.replace(" ", ""), 2)] = count
        return result

    @staticmethod
    def _decode(counts, lo, hi, local, rng):
        if local:
            fraction = np.sqrt(counts / counts.sum())
        else:
            spread = np.ptp(counts)
            if spread == 0:
                # Eq. (16) is undefined for equal counts; retain global exploration.
                return rng.uniform(lo, hi, size=counts.size)
            fraction = (counts - counts.min()) / spread
        values = lo + (hi - lo) * fraction
        # Paper Algorithm 2: replace exact lower-bound outcomes with random draws.
        at_lower = values == lo
        values[at_lower] = rng.uniform(lo, hi, size=np.count_nonzero(at_lower))
        return np.clip(values, lo, hi)

    def _record(self, population, losses, generation, verbose):
        best = int(np.argmin(losses))
        self._p = population[best].copy()
        self.loss_ = float(losses[best])
        self.n_generations_ = generation
        self.history_.append({
            "generation": generation, "loss": self.loss_, "p": self.p,
            "loss_kind": self.loss_kind_, "best_index": best,
            "population": [
                {"p": parameters.tolist(), "loss": float(loss),
                 "chi2": float(loss) if self.loss_kind_ == "chi2" else None}
                for parameters, loss in zip(population, losses)
            ],
        })
        if verbose and (generation == 0 or generation % 10 == 0):
            print(f"generation={generation:4d} loss={self.loss_:.8g} p={self.p}")

    def _predict(self, inputs, parameters):
        features = 1 if inputs.ndim == 1 else inputs.shape[1]
        if hasattr(self, "_n_features") and features != self._n_features:
            raise ValueError("x must have the same number of features as the training data.")
        if self.vectorized:
            prediction = self.function(inputs.tolist(), parameters.tolist())
        else:
            rows = inputs.reshape(-1, 1) if inputs.ndim == 1 else inputs
            prediction = [self.function(row.tolist(), parameters.tolist()) for row in rows]
        raw = np.asarray(prediction)
        if np.iscomplexobj(raw):
            raise ValueError("function must return real predictions.")
        values = np.asarray(raw, dtype=float)
        if values.shape != (len(inputs),):
            raise ValueError(
                "function must return one scalar per sample (default), or a list/array "
                "of shape (n_samples,) with vectorized=True. "
                f"Received prediction shape {values.shape}."
            )
        return values

    @staticmethod
    def _weights(size, sigma, covariance):
        if sigma is not None and covariance is not None:
            raise ValueError("Provide either sigma or covariance, not both.")
        if sigma is not None:
            scale = AEQGA._real_array(sigma, "sigma")
            if scale.ndim != 0 and scale.shape != (size,):
                raise ValueError("sigma must be a scalar or a list of length n_samples.")
            if np.any(scale <= 0):
                raise ValueError("All standard deviations in sigma must be positive.")
            return scale, None
        if covariance is not None:
            matrix = AEQGA._real_array(covariance, "covariance")
            if matrix.shape != (size, size):
                raise ValueError("covariance must have shape (n_samples, n_samples).")
            if not np.allclose(matrix, matrix.T, rtol=1e-10, atol=1e-12):
                raise ValueError("covariance must be symmetric.")
            try:
                cholesky = np.linalg.cholesky(matrix)
            except np.linalg.LinAlgError as exc:
                raise ValueError("covariance must be positive definite.") from exc
            return None, cholesky
        return None, None

    @staticmethod
    def _real_array(value, name):
        raw = np.asarray(value)
        if np.iscomplexobj(raw):
            raise ValueError(f"{name} must contain real numbers.")
        array = np.asarray(raw, dtype=float)
        if not np.all(np.isfinite(array)):
            raise ValueError(f"{name} must contain only finite values.")
        return array

    @staticmethod
    def _inputs(x):
        array = AEQGA._real_array(x, "x")
        if array.ndim not in (1, 2) or array.size == 0:
            raise ValueError("x must be a nonempty one- or two-dimensional list of samples.")
        return array

    @staticmethod
    def _positive_integer(value, name):
        if isinstance(value, bool) or not isinstance(value, Integral) or value <= 0:
            raise ValueError(f"{name} must be a positive integer.")
